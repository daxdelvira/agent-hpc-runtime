# ---------------------------------------------------------------- setfl ----
def make_setfl(path: str, n: int, element: str = "W") -> str:
    """A synthetic eam/alloy table with n points per array.

    The login node has a 4 GiB per-user cgroup cap (memory.max), which SIGKILLed
    a full-size LAMMPS run twice during the COW work, so the local arm needs a
    right-sized artifact. The ENERGIES ARE NOT PHYSICAL -- this measures parse
    cost and footprint, and every physics comparison in this script is
    retained-vs-fork on the SAME table, so a non-physical potential cannot
    flatter the correctness gate.
    """
    import math
    nrho, drho = n, 1.0 / n
    nr, dr = n, 5.0 / n
    with open(path, "w") as f:
        f.write("synthetic setfl load generator (non-physical)\n")
        f.write("generated by experiments/bench_residency_data_worker.py\n")
        f.write("not a validated potential; parse-cost and footprint only\n")
        f.write(f"1 {element}\n")
        f.write(f"{nrho} {drho!r} {nr} {dr!r} 5.0\n")
        f.write("74 183.84 3.165 bcc\n")
        buf = []
        for i in range(nrho):
            buf.append(f"{-math.sqrt(i * drho) * 1.0:.10e}")
            if len(buf) == 5:
                f.write(" ".join(buf) + "\n"); buf = []
        if buf:
            f.write(" ".join(buf) + "\n"); buf = []
        for i in range(nr):
            buf.append(f"{math.exp(-3.0 * i * dr):.10e}")
            if len(buf) == 5:
                f.write(" ".join(buf) + "\n"); buf = []
        if buf:
            f.write(" ".join(buf) + "\n"); buf = []
        for i in range(nr):
            r = i * dr
            buf.append(f"{(0.0 if r == 0 else 100.0 * math.exp(-2.0 * r)):.10e}")
            if len(buf) == 5:
                f.write(" ".join(buf) + "\n"); buf = []
        if buf:
            f.write(" ".join(buf) + "\n")
    return path


# -------------------------------------------------------------- geometry ---
GEOM_A = ("lattice bcc 3.165", "region box block 0 2 0 2 0 2")
GEOM_B = ("lattice bcc 3.165 orient x 1 -1 2 orient y 1 1 0 orient z -1 1 1",
          "region box block 0 4 0 4 0 3")

SETUP = ["units metal", "boundary p p p", "atom_style atomic",
         GEOM_A[0], GEOM_A[1], "create_box 1 box", "create_atoms 1 box",
         "mass 1 183.84", "neigh_modify one 10000 page 1000000"]


def _style_for(p: str) -> str:
    return "eam/fs" if p.endswith(".fs") else "eam/alloy"


# ------------------------------------------------------------ client body --
_CLIENT = r'''
import json, os, sys, time
t0 = time.perf_counter()
from lammps import lammps
lmp = lammps(cmdargs=["-log", {log!r}, "-screen", "none"])
if type(lmp).__module__ != "lammps" or not hasattr(lmp, "worker_stats"):
    print(json.dumps({{"error": "shim did not proxy; this would be a fresh parse"}}))
    sys.exit(3)
for c in {cmds!r}:
    lmp.command(c)
rec = {{"natoms": lmp.get_natoms(), "pe": lmp.get_thermo("pe"),
        "elapsed_s": time.perf_counter() - t0,
        "worker": lmp.worker_stats()}}
{extra}
lmp.close()
print(json.dumps(rec))
'''

_SEGV = r'''
import ctypes
ctypes.string_at(1)          # deliberate SIGSEGV in the CLIENT process
'''


def write_client(tmp: Path, name: str, cmds: list[str], log: str,
                 extra: str = "") -> str:
    p = tmp / name
    p.write_text(_CLIENT.format(log=log, cmds=cmds, extra=textwrap.dedent(extra)))
    return str(p)


def run_client(script: str, sock: str, python: str, cwd: str,
               strict: bool = True) -> tuple[dict, float, subprocess.CompletedProcess]:
    env = os.environ.copy()
    env["TANDEM_LAMMPS_SOCKET"] = sock
    if strict:
        env["TANDEM_LAMMPS_STRICT"] = "1"
    env["PYTHONPATH"] = os.pathsep.join(
        [str(SHIM_DIR)] + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))
    t0 = time.perf_counter()
    r = subprocess.run([python, script], env=env, cwd=cwd,
                       capture_output=True, text=True)
    dt = time.perf_counter() - t0
    rec = {}
    for line in r.stdout.splitlines():
        line = line.strip()
        if line.startswith("{"):
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                pass
    return rec, dt, r


# ------------------------------------------------------------- fork path ---
_FORK = r'''
import json, sys, time
from lammps import lammps
pot, style, log = sys.argv[1], sys.argv[2], sys.argv[3]
cmds = json.loads(sys.argv[4])
t0 = time.perf_counter()
lmp = lammps(cmdargs=["-log", log, "-screen", "none"])
for c in cmds:
    lmp.command(c)
lmp.command("pair_style %s" % style)
t1 = time.perf_counter()
lmp.command("pair_coeff * * %s W" % pot)
lmp.command("run 0")
parse_s = time.perf_counter() - t1
rec = {"natoms": lmp.get_natoms(), "pe": lmp.get_thermo("pe"),
       "parse_s": parse_s, "total_s": time.perf_counter() - t0}
print(json.dumps(rec))
'''


def fork_run(python: str, tmp: Path, pot: str, style: str, setup: list[str],
             log: str, cwd: str) -> tuple[dict, float]:
    s = tmp / "fork_arm.py"
    s.write_text(_FORK)
    t0 = time.perf_counter()
    r = subprocess.run([python, str(s), pot, style, log, json.dumps(setup)],
                       capture_output=True, text=True, cwd=cwd)
    dt = time.perf_counter() - t0
    if r.returncode != 0:
        raise RuntimeError(f"fork arm failed: {r.stderr[-2000:]}")
    return json.loads(r.stdout.strip().splitlines()[-1]), dt


# ------------------------------------------------------------------ main ---
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--potential", default=None,
                    help="real potential; omit to generate a synthetic setfl")
    ap.add_argument("--synthetic-n", type=int, default=1_500_000)
    ap.add_argument("--tmp", default="/tmp",
                    help="node-local NVMe. Lustre makes fadvise a silent no-op.")
    ap.add_argument("--out", default="results/bench_residency_data_worker.json")
    ap.add_argument("--python", default=sys.executable)
    a = ap.parse_args()

    host = os.uname().nodename
    tmp = Path(a.tmp) / f"tandem_bench_{os.getpid()}"
    tmp.mkdir(parents=True, exist_ok=True)
    out: dict = {"host": host, "python": a.python,
                 "started": time.strftime("%Y-%m-%dT%H:%M:%S"),
                 "cgroup_memory_max": _cgroup_max()}

    if a.potential:
        pot = os.path.abspath(a.potential)
        out["potential_kind"] = "real"
    else:
        pot = str(tmp / "synthetic.eam.alloy")
        t0 = time.perf_counter()
        make_setfl(pot, a.synthetic_n)
        out["potential_kind"] = "synthetic"
        out["synthetic_n"] = a.synthetic_n
        out["synthetic_gen_s"] = round(time.perf_counter() - t0, 2)
    style = _style_for(pot)
    out.update(potential=pot, potential_gb=round(os.path.getsize(pot) / 1e9, 4),
               pair_style=style)
    print(f"host {host}\npotential {pot} ({out['potential_gb']} GB, {style})",
          flush=True)

    # ---------------- D4 ground truth: the fork path -----------------------
    print("\n[fork] ground truth, one fresh instance per geometry", flush=True)
    fork = []
    for i, g in enumerate((GEOM_A, GEOM_B)):
        setup = [c if not c.startswith("lattice") else g[0] for c in SETUP]
        setup = [c if not c.startswith("region") else g[1] for c in setup]
        rec, wall = fork_run(a.python, tmp, pot, style, setup,
                             str(tmp / f"fork_{i}.log"), str(tmp))
        rec.update(geometry=i, wall_s=round(wall, 3))
        fork.append(rec)
        print(f"  geom{i}: n={rec['natoms']} pe={rec['pe']:.12g} "
              f"parse {rec['parse_s']:.2f}s wall {wall:.2f}s", flush=True)
    out["fork"] = fork
    # A second fork run for geom0 with the page cache now warm: this is the
    # honest COLD-PER-CALL number for a workload that reruns the same file.
    rec, wall = fork_run(a.python, tmp, pot, style, SETUP,
                         str(tmp / "fork_warm.log"), str(tmp))
    out["fork_warm_repeat"] = {"parse_s": round(rec["parse_s"], 3),
                               "wall_s": round(wall, 3), "pe": rec["pe"]}
    print(f"  warm repeat: parse {rec['parse_s']:.2f}s wall {wall:.2f}s",
          flush=True)

    # ---------------- stage the worker -------------------------------------
    spec = ResourceSpec(
        resource_id="bench_potential",
        resource_class=ResourceClass.DATA_PATTERN_B,
        held_rung=Rung.R3_ACTIVATED,
        held_gb=max(out["potential_gb"], 0.001),   # provisional; measured below
        cold_s=max(rec["parse_s"], 0.001),
        ready_s=0.0,
    )
    actor = LammpsDataWorker(
        artifacts={"bench_potential": {"potential": pot, "pair_style": style,
                                       "setup": SETUP, "element": "W"}},
        python=a.python, socket_dir=a.tmp, atomagents_root=ATOMAGENTS_ROOT,
        verbose=False)
    print("\n[stage] activating in the resident worker", flush=True)
    t0 = time.perf_counter()
    rung = actor.stage(spec)
    stage_s = time.perf_counter() - t0
    det = actor.activation_detail("bench_potential")
    smaps = read_smaps_rollup(det["pid"])
    out["stage"] = {"rung": int(rung), "rung_name": rung.name,
                    "stage_wall_s": round(stage_s, 3), **det,
                    "worker_smaps_gb": {k: round(v, 4) for k, v in smaps.items()},
                    "threads_at_start": det["threads_at_start"]}
    print(f"  rung {rung.name}  activate {det['activate_s']:.2f}s  "
          f"Private_Dirty {det['private_dirty_gb']:.3f} GB  "
          f"(Rss {smaps.get('Rss', 0):.3f} GB -- NOT the budget number)  "
          f"threads_at_start {det['threads_at_start']}", flush=True)
    if rung != Rung.R3_ACTIVATED:
        print("  staging did not reach R3; aborting", flush=True)
        return 2
    sock = actor.socket_for("bench_potential")

    # ---------------- D1 + D4: reuse through the shim ----------------------
    print("\n[reuse] generated-style scripts against the live worker", flush=True)
    reuse = []
    for i, g in enumerate((GEOM_A, GEOM_B)):
        cmds = [g[0], g[1], "create_box 1 box", "create_atoms 1 box",
                "mass 1 183.84", "neigh_modify one 10000 page 1000000",
                f"pair_style {style}", f"pair_coeff * * {pot} W", "run 0",
                "quit"]
        sc = write_client(tmp, f"client_{i}.py", cmds, str(tmp / f"reuse_{i}.log"))
        r, wall, cp = run_client(sc, sock, a.python, str(tmp))
        if cp.returncode != 0 or "pe" not in r:
            print(f"  FAILED rc={cp.returncode}\n{cp.stdout[-2000:]}\n"
                  f"{cp.stderr[-3000:]}", flush=True)
            actor.release_all()
            return 3
        r.update(geometry=i, wall_s=round(wall, 3))
        reuse.append(r)
        print(f"  geom{i}: n={r['natoms']} pe={r['pe']:.12g} "
              f"in-script {r['elapsed_s']:.2f}s wall {wall:.2f}s "
              f"parses_avoided={r['worker']['rewriter']['parses_avoided']} "
              f"quits_suppressed={r['worker']['quits_suppressed']}", flush=True)
    out["reuse"] = reuse

    # D4 gate
    gate = []
    ok = True
    for f, r in zip(fork, reuse):
        rel = (abs(r["pe"] - f["pe"]) / abs(f["pe"])) if f["pe"] else abs(r["pe"])
        passed = (f["natoms"] == r["natoms"]) and rel == 0.0
        ok &= passed
        gate.append({"geometry": f["geometry"], "natoms_fork": f["natoms"],
                     "natoms_retained": r["natoms"], "pe_fork": f["pe"],
                     "pe_retained": r["pe"], "pe_rel_diff": rel,
                     "passed": bool(passed)})
        print(f"  D4 geom{f['geometry']}: pe rel diff {rel:.3e} "
              f"-> {'PASS' if passed else 'FAIL'}", flush=True)
    out["D4_correctness"] = {"comparisons": gate, "PASS": bool(ok)}

    # D1 ratio
    cold_s = out["fork_warm_repeat"]["parse_s"]
    warm_s = reuse[-1]["elapsed_s"]
    out["D1_residency"] = {
        "node": host,
        "cold_warm_parse_s": round(cold_s, 3),
        "live_reuse_in_script_s": round(warm_s, 3),
        "ratio": round(cold_s / warm_s, 3) if warm_s else None,
        "cold_wall_s": out["fork_warm_repeat"]["wall_s"],
        "reuse_wall_s": reuse[-1]["wall_s"],
        "wall_ratio": round(out["fork_warm_repeat"]["wall_s"]
                            / reuse[-1]["wall_s"], 3),
    }
    print(f"\n[D1] {host}: cold warm-parse {cold_s:.2f}s vs live reuse "
          f"{warm_s:.2f}s = {out['D1_residency']['ratio']}x "
          f"(wall {out['D1_residency']['wall_ratio']}x)", flush=True)

    # ---------------- crash isolation --------------------------------------
    print("\n[crash] client segfaults mid-session", flush=True)
    pe_before = reuse[-1]["pe"]
    crash = tmp / "client_segv.py"
    crash.write_text(
        "import os\n"
        "from lammps import lammps\n"
        f"lmp = lammps(cmdargs=['-log', {str(tmp / 'segv.log')!r}, '-screen', 'none'])\n"
        "lmp.command('run 0')\n" + _SEGV)
    _, _, cp = run_client(str(crash), sock, a.python, str(tmp))
    worker_pid = det["pid"]
    time.sleep(0.5)
    alive = Path(f"/proc/{worker_pid}").exists()
    after = {}
    if alive:
        sc = write_client(tmp, "client_after_crash.py", ["run 0"],
                          str(tmp / "after_crash.log"))
        after, _, cp2 = run_client(sc, sock, a.python, str(tmp))
    out["crash_isolation"] = {
        "client_returncode": cp.returncode,
        "client_signalled": cp.returncode < 0,
        "worker_alive_after": alive,
        "pe_before": pe_before,
        "pe_after": after.get("pe"),
        "pe_identical": after.get("pe") == pe_before,
        "held_gb_after": actor.measure_held_gb("bench_potential"),
    }
    print(f"  client rc={cp.returncode} (negative = killed by signal); "
          f"worker alive={alive}; pe identical="
          f"{out['crash_isolation']['pe_identical']}", flush=True)

    # ---------------- D2 eviction ------------------------------------------
    print("\n[D2] eviction", flush=True)
    held = actor.measure_held_gb("bench_potential")
    cg_before = cgroup_current_gb()
    t0 = time.perf_counter()
    freed = actor.release("bench_potential")
    release_s = time.perf_counter() - t0
    witness = actor.release_witness("bench_potential")
    detail = actor.last_release_detail["bench_potential"]
    cg_after = cgroup_current_gb()
    out["D2_eviction"] = {
        "held_before_gb": round(held, 4),
        "release_returned_gb": round(freed, 4),
        "release_s": round(release_s, 3),
        # The independent witness the ledger asks for: the job cgroup's anon
        # total either side of the release. It does not depend on the released
        # process still existing, which is what makes it independent of a
        # teardown actor's by-construction 0.0.
        "release_witness_gb": witness,
        "witness_measured_by": detail.get("witness_measured_by"),
        "detail": detail,
        "cgroup_before_gb": None if cg_before is None else round(cg_before, 4),
        "cgroup_after_gb": None if cg_after is None else round(cg_after, 4),
        "cgroup_freed_gb": (None if (cg_before is None or cg_after is None)
                            else round(cg_before - cg_after, 4)),
        "measure_held_gb_after": actor.measure_held_gb("bench_potential"),
        "is_resident_after": actor.is_resident("bench_potential"),
        "proc_entry_gone": not Path(f"/proc/{worker_pid}").exists(),
    }
    print(f"  release returned {freed:.3f} GB  (in-process close freed "
          f"{detail.get('in_process_freed_gb')} GB before teardown)\n"
          f"  release_witness (cgroup anon delta) {witness} GB  "
          f"[{detail.get('cgroup_anon_before_gb')} -> "
          f"{detail.get('cgroup_anon_after_gb')}]\n"
          f"  cgroup memory.current {out['D2_eviction']['cgroup_freed_gb']} GB "
          f"lower  /proc/{worker_pid} gone="
          f"{out['D2_eviction']['proc_entry_gone']}", flush=True)

    # (a) the client must now FAIL rather than quietly re-parse
    sc = write_client(tmp, "client_after_release.py", ["run 0"],
                      str(tmp / "after_release.log"))
    _, _, cp3 = run_client(sc, sock, a.python, str(tmp), strict=True)
    out["D2_eviction"]["client_after_release_rc"] = cp3.returncode
    out["D2_eviction"]["client_after_release_refused"] = cp3.returncode != 0
    print(f"  client against the released worker: rc={cp3.returncode} "
          f"(non-zero = refused, not silently re-parsed)", flush=True)

    # (b) THE BEHAVIOURAL PROOF: the next use pays cold again
    print("  re-staging: the next use must pay a COLD cost", flush=True)
    t0 = time.perf_counter()
    rung2 = actor.stage(spec)
    restage_s = time.perf_counter() - t0
    det2 = actor.activation_detail("bench_potential")
    out["D2_eviction"]["restage"] = {
        "rung": rung2.name, "wall_s": round(restage_s, 3),
        "activate_s": det2.get("activate_s"),
        "private_dirty_gb": det2.get("private_dirty_gb"),
        "vs_live_reuse_s": round(warm_s, 3),
        "cold_again_ratio": (round(det2["activate_s"] / warm_s, 3)
                             if warm_s and det2.get("activate_s") else None),
    }
    out["D2_eviction"]["witness_after_restage"] = actor.release_witness("bench_potential")
    out["D2_eviction"]["witness_goes_stale"] = (
        out["D2_eviction"]["witness_after_restage"] is None)
    print(f"  witness after re-stage: "
          f"{out['D2_eviction']['witness_after_restage']} "
          f"(None = the stale-witness guard held)", flush=True)
    print(f"  re-activate {det2.get('activate_s')}s vs live reuse "
          f"{warm_s:.2f}s -> the saving is gone, as it must be", flush=True)
    actor.release_all()

    out["finished"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    op = Path(a.out)
    op.parent.mkdir(parents=True, exist_ok=True)
    if op.exists():
        bak = op.with_suffix(op.suffix + f".bak.{int(time.time())}")
        bak.write_bytes(op.read_bytes())
        print(f"\nbacked up existing {op} -> {bak}")
    op.write_text(json.dumps(out, indent=2))
    print(f"wrote {op}")
    return 0 if ok else 1


def _cgroup_max() -> str | None:
    try:
        for line in open("/proc/self/cgroup"):
            parts = line.strip().split(":", 2)
            if len(parts) == 3 and parts[0] == "0":
                p = Path("/sys/fs/cgroup") / parts[2].lstrip("/") / "memory.max"
                if p.exists():
                    return p.read_text().strip()
    except OSError:
        pass
    return None


if __name__ == "__main__":
    raise SystemExit(main())
