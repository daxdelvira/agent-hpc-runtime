#!/usr/bin/env python3
"""bench_residency_data_worker.py — D1/D2/D4 for the resident data worker (T4b).

    $ATOMS_PYTHON experiments/bench_residency_data_worker.py \
        --potential workloads/AtomAgents/potential_repository/w_eam4_big.fs \
        --out results/bench_residency_data_worker.json

WHAT EACH ARM IS FOR, AND WHAT WOULD MAKE IT A LIE.

D1 residency. `cold` parses the potential in a fresh process; `reuse` runs a
    generated-style script through the shim against an already-activated
    worker. The ratio is the claim. THE LIE TO GUARD AGAINST is a silent
    fallback: if the shim could not reach the worker it would construct a real
    instance and the "reuse" arm would just be another cold parse that happened
    to be fast. Every client here runs with TANDEM_LAMMPS_STRICT=1, which turns
    an unreachable worker into an exception instead of a plausible number.

D2 eviction. The one most likely to fail silently. Three separate checks, none
    of which is "the process exited, so the memory must be back":
      (a) Private_Dirty from /proc/<pid>/smaps_rollup immediately before
          teardown — never Rss, which double-counts shared pages and in the COW
          benchmark would have made a failed copy-on-write look successful;
      (b) the enclosing cgroup's memory.current delta across the release, as an
          INDEPENDENT witness;
      (c) the behavioural test that actually matters: after the release, the
          next use pays a measured COLD cost again. A release that frees nothing
          while reporting success would leave the next use fast.
    Also run: an in-process `close()` measurement, reported separately, because
    glibc arena retention can make a successful free invisible in Private_Dirty.

D4 correctness. `pe` from the retained path against `pe` from the fork path
    (a fresh instance per geometry), the gate already used by
    results/verify_persistent_lammps_BIG.json. Required: relative difference
    exactly 0.000e+00. A retention that changes the answer is not a speedup.

CRASH ISOLATION. A client subprocess is made to segfault mid-session; the
    worker must survive with the structure intact and return the SAME pe.

ALL RATIOS ARE REPORTED WITH THE NODE NAMED. The same warm parse measured
42.83 s on a Blackwell node and 98.23 s on another — a 2.3x CPU difference —
so an absolute second-count without a hostname is not a result.
"""
